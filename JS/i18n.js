export function interpolate(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) =>
    values[key] == null ? "" : String(values[key])
  );
}

export function t(lang, key, values) {
  const table = translations[lang] || translations.en;
  const text = table[key] ?? translations.en[key] ?? key;
  return values ? interpolate(text, values) : text;
}

export function applyStaticTranslations(lang) {
  const table = translations[lang] || translations.en;

  document.documentElement.lang = table.lang;
  document.documentElement.dir = table.dir;
  document.title = table.documentTitle;

  document.querySelectorAll("[data-i18n]").forEach(node => {
    node.textContent = t(lang, node.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(node => {
    node.placeholder = t(lang, node.dataset.i18nPlaceholder);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(node => {
    node.setAttribute("aria-label", t(lang, node.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-title]").forEach(node => {
    node.setAttribute("title", t(lang, node.dataset.i18nTitle));
  });
}

export function greetingFor(lang, name, tasks) {
  if (!name) {
    return t(lang, "greetingFallback");
  }

  const pending = tasks.filter(task => !task.isDone);
  const completed = tasks.filter(task => task.isDone);
  const firstPending = pending[0]?.title ?? "";

  if (pending.length === 1) {
    return t(lang, "greetingPendingOne", { name, task: firstPending });
  }

  if (pending.length > 1) {
    return t(lang, "greetingPendingMany", {
      name,
      count: pending.length,
      task: firstPending
    });
  }

  if (completed.length && !pending.length) {
    return t(lang, "greetingAllDone", { name });
  }

  if (completed.length) {
    return t(lang, "greetingCompletedHint", {
      name,
      count: completed.length
    });
  }

  return t(lang, "greetingHello", { name });
}
